import json, pandas as pd
from .config import *
from .data_loader import load_raw
from .validation import validate
from .kpis import *

def build():
    PROC.mkdir(parents=True, exist_ok=True)
    raw = load_raw(); checks, anomalies = validate(raw)
    df = flag_risk(add_kpis(raw))
    df.to_parquet(PROC / "skycity_validated.parquet", index=False); df.to_csv(PROC / "skycity_validated.csv", index=False)
    ct = channel_table(df); fs = df[df.Segment == "Full-service"]
    arev = lambda x: x[REV["Uber Eats"]] + x[REV["DoorDash"]]
    S = {"venues": len(df), "orders": int(df.MonthlyOrders.sum()), "revenue": float(df.TotalRevenue.sum()), "net_profit": float(df.TotalNetProfit.sum()),
         "channels": ct.to_dict("index"), "agg_order_share": float(ct.loc[AGGREGATORS, "OrderShare"].sum()), "agg_profit_share": float(ct.loc[AGGREGATORS, "ProfitShare"].sum()),
         "agg_margin": float(ct.loc[AGGREGATORS, "NetProfit"].sum() / ct.loc[AGGREGATORS, "Revenue"].sum()),
         "direct_profit_share": float(ct.loc[["In-Store", "Self-Delivery"], "ProfitShare"].sum()),
         "subregions": group_table(df, "Subregion").to_dict("index"), "cuisines": group_table(df, "CuisineType").to_dict("index"),
         "segments": group_table(df, "Segment").to_dict("index"), "dominance": dominance(df).to_dict("index"),
         "projection": projection(df).to_dict("index"),
         "risk": {"tier1": int(df.Tier1.sum()), "tier2": int(df.Tier2.sum()), "both": int((df.Tier1 & df.Tier2).sum()), "loss_either": int(df.LossOnEither.sum()),
                  "tier2_fullservice": int(fs.Tier2.sum()), "tier2_other": int(df[df.Segment != "Full-service"].Tier2.sum()),
                  "single_ge_70": int((df.Single_Agg_Max >= .7).sum()), "combined_ge_70": int((df.ADI_Total >= .7).sum())},
         "fullservice": {"venues": len(fs), "agg_profit": float(fs.Agg_NetProfit.sum()), "agg_margin": float(fs.Agg_NetProfit.sum() / arev(fs).sum()),
                         "ue_profit": float(fs[PRF["Uber Eats"]].sum()), "dd_profit": float(fs[PRF["DoorDash"]].sum()), "orders": int(fs.MonthlyOrders.sum()),
                         "segment_net": float(fs.TotalNetProfit.sum()), "breakeven_at_cap": breakeven_share(fs, SIM_CAP),
                         "sd_margin": float(fs[PRF["Self-Delivery"]].sum() / fs[REV["Self-Delivery"]].sum()),
                         "capped_agg_margin": float((fs.Agg_NetProfit + (fs.CommissionRate - SIM_CAP).clip(lower=0) * arev(fs)).sum() / arev(fs).sum())},
         "sim_shift": simulate(df, SIM_SHIFT, "Self-Delivery", None), "sim_cap": simulate(df, 0, "Self-Delivery", SIM_CAP),
         "sd_cost_max_pct_of_aov": float((df.DeliveryCostOrder / df.AOV).max()), "commission_min": float(df.CommissionRate.min()), "commission_max": float(df.CommissionRate.max()),
         "commission_wtd": float((arev(df) * df.CommissionRate).sum() / arev(df).sum()), "commission_monthly": float((arev(df) * df.CommissionRate).sum()),
         "checks": [list(x) for x in checks], "anomalies": [list(x) for x in anomalies]}
    json.dump(S, open(PROC / "kpi_summary.json", "w"), indent=1, default=float)
    with open(ROOT / "docs/ANOMALY_LOG.md", "w") as f:
        f.write("# Anomaly Log (generated by `python -m src.pipeline`)\n\n| ID | Topic | Finding | Resolution |\n|---|---|---|---|\n")
        for i, t, fnd, r in anomalies: f.write(f"| {i} | {t} | {fnd} | {r} |\n")
        f.write("\n## Gate 1 checks\n\n" + "\n".join(f"- {'PASS' if ok else 'FAIL'}: {n} {d}" for n, ok, d in checks) + "\n")
    return df, S

if __name__ == "__main__":
    df, S = build(); print("rows", len(df)); print(*[("PASS" if o else "FAIL", n) for n, o, _ in S["checks"]], sep="\n")
